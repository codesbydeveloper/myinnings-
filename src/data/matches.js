export function getMatchesForTeam(teamName, list = MATCHES) {
  return list.filter((match) => match.home === teamName || match.away === teamName)
}

export function getUpcomingMatchCount(teamName, list = MATCHES) {
  return getMatchesForTeam(teamName, list).filter(
    (match) => match.status === 'Upcoming' || match.status === 'Live',
  ).length
}
